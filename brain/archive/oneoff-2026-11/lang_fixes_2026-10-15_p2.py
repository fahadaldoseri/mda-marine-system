#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""الجزء الثاني من تصحيحات التدقيق اللغوي/المصطلحي لتقرير 15 أكتوبر 2026.

يغطي المواضع المتبقية في المتن وملف واجهة الموقع (التحذيرات، وصف السفن المنتظرة، «إغراق/غرق»).

الاستخدام: python3 tools/lang_fixes_2026-10-15_p2.py [--dry]
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGETS = [
    ROOT / "reports" / "2026-10-15-sectioned.md",
    ROOT / "web" / "meta" / "2026-10-15.json",
]

FIXES = [
    # المتن
    ("مصطلح معتمد: Warning = تحذير", "لا إنذارات سارية وكل النشرات السابقة ملغاة أو منتهية",
     "لا تحذيرات سارية وكل النشرات السابقة ملغاة أو منتهية"),
    ("كلمة غير دارجة: «ممسكة بموضعها»", "وعدد السفن الممسكة بموضعها", "وعدد السفن الواقفة في مواضعها"),
    # ملف الواجهة
    ("مصطلح معتمد: Warning = تحذير", "صفحة الإنذارات البحرية الرسمية", "صفحة التحذيرات البحرية الرسمية"),
    ("مصطلح معتمد: Warning = تحذير", '"name": "إنذارات بحرية أمريكية سارية"', '"name": "تحذيرات بحرية أمريكية سارية"'),
    ("كلمة غير دارجة: «ممسكة بموضعها»", '"label": "سفن ممسكة بموضعها بعيدًا عن المراسي"',
     '"label": "سفن واقفة في مواضعها بعيدًا عن المراسي"'),
    ("كلمة غير دارجة: «ممسكة بموضعها»", '"name": "سفن ممسكة بموضعها بعيدًا عن المراسي"',
     '"name": "سفن واقفة في مواضعها بعيدًا عن المراسي"'),
    ("دقة قانونية/عسكرية: «إغراق» للغرق المتعمد فقط", "لكن ثقل النتيجة تغيّر: إغراق فعلي", "لكن ثقل النتيجة تغيّر: غرق فعلي"),
    ("دقة قانونية/عسكرية: «إغراق» للغرق المتعمد فقط", '"text": "+2 — أول إغراق منذ مارس"', '"text": "+2 — أول غرق منذ مارس"'),
    ("دقة قانونية/عسكرية: «إغراق» للغرق المتعمد فقط", "من ضرر إلى إغراق.", "من ضرر إلى غرق."),
    ("مصطلح معتمد: لا «هجوم» بلا ثبوت", '"estimate": "استمرار هجمات منظمة على السفن في المضيق"',
     '"estimate": "استمرار الاستهداف المنظم للسفن في المضيق"'),
]


def main():
    dry = "--dry" in sys.argv
    total = 0
    for path in TARGETS:
        text = path.read_text(encoding="utf-8")
        hits = []
        for reason, old, new in FIXES:
            n = text.count(old)
            if n:
                hits.append((reason, old, new, n))
                if not dry:
                    text = text.replace(old, new)
        if hits and not dry:
            if path.suffix == ".json":
                json.loads(text)
            path.write_text(text, encoding="utf-8")
        total += sum(h[3] for h in hits)
        print(f"{'[تجريبي] ' if dry else ''}{path.name}: {sum(h[3] for h in hits)} استبدالًا")
        for reason, old, new, n in hits:
            print(f"  · [{reason}] ×{n}: {old[:50]} → {new[:50]}")
    print(f"الإجمالي: {total}")
    return 0


if __name__ == "__main__":
    sys.exit(main())