def main() -> int:
    applied, missing = 0, []
    for rel, old, new, why in EDITS:
        p = ROOT / rel
        t = p.read_text(encoding="utf-8")
        if old not in t:
            missing.append((rel, old[:60], why))
            continue
        p.write_text(t.replace(old, new, 1), encoding="utf-8")
        applied += 1
        print(f"  ✔ {Path(rel).name}: {why}")
    print(f"\nطُبِّق: {applied} · لم يُعثر على النص: {len(missing)}")
    for rel, old, why in missing:
        print(f"  ✘ {Path(rel).name} — «{old}…» ({why})")
    return 1 if missing else 0


