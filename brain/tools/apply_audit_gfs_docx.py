def rpr_rtl(run):
    rPr = run._element.get_or_add_rPr()
    for tag in ('w:rtl', 'w:cs'):
        el = rPr.find(qn(tag))
        if el is None:
            el = rPr.makeelement(qn(tag), {})
            rPr.append(el)
        el.set(qn('w:val'), '1')


def para_bidi(p):
    pPr = p._element.get_or_add_pPr()
    if pPr.find(qn('w:bidi')) is None:
        el = pPr.makeelement(qn('w:bidi'), {})
        el.set(qn('w:val'), '1')
        pPr.insert(0, el)


def _write_run(run, text):
    r = run._element
    for child in list(r):
        if child.tag in (qn('w:t'), qn('w:br'), qn('w:tab')):
            r.remove(child)
    parts = text.split('\n')
    for i, part in enumerate(parts):
        if i > 0:
            r.append(r.makeelement(qn('w:br'), {}))
        t = r.makeelement(qn('w:t'), {})
        t.text = part
        t.set(qn('xml:space'), 'preserve')
        r.append(t)


def set_para(p, text):
    """يستبدل نص الفقرة محافظًا على التنسيق: يحتفظ بالعنوان القصير في أول تشكيلة."""
    runs = p.runs
    if not runs:
        r = p.add_run(text)
        rpr_rtl(r)
        return
    old0 = runs[0].text.strip()
    label = ''
    if 0 < len(old0) <= 22 and '.' in old0:
        label = old0[:old0.index('.') + 1]
    if label and text.startswith(label):
        runs[0].text = label
        rest = text[len(label):]
        if len(runs) > 1:
            _write_run(runs[1], rest)
            for r in runs[2:]:
                _write_run(r, '')
        else:
            r2 = p.add_run(rest)
            rpr_rtl(r2)
    else:
        _write_run(runs[0], text)
        for r in runs[1:]:
            _write_run(r, '')
    for r in p.runs:
        rpr_rtl(r)


def set_cell(cell, text):
    set_para(cell.paragraphs[0], text)
    for extra in cell.paragraphs[1:]:
        set_para(extra, '')


def key_ok(p, key):
    return key in p.text


