#!/usr/bin/env bash
# الاسم محفوظ للتوافق الخلفي فقط: النسخة الاحتياطية صارت على GitHub في المستودع الخاص.
# أُخرجت النسخة المكرّرة `brain-backup/` من مستودع الموقع بعد وجود المستودع الخاص
# (المصدر الوحيد للنسخة — راجع audit/سجل-الأعطال-والثغرات.md: ك-06).
set -u
_B="${BRAIN_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
echo "  ملاحظة: النسخة الاحتياطية تُدفع الآن إلى المستودع الخاص عبر github_backup.sh"
exec bash "$_B/tools/github_backup.sh" "$@"
