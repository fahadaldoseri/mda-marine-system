#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""إعادة ترتيب أقسام التقرير اليومي وفق الأهمية (القرار والصورة ← الوقائع ← التحليل ← الدعم).

يطبّق الترتيب في: المولّد الموحّد · مرجع الأقسام · مرجع الكتل · قاعدة ك1 · أرشيف تقرير 12 أكتوبر.
"""
# ── مسارات النظام: محمولة (تُقرأ من BRAIN_DIR / SITE_DIR، والافتراضي جذر الشجرة) ──
import os as _os
from pathlib import Path as _Path
_ROOT = _Path(__file__).resolve().parents[1]
BRAIN = _Path(_os.environ.get("BRAIN_DIR") or _ROOT)

def _tree(_env, _base, *_names):
    """جذر الشجرة المجاورة: من متغيّر البيئة أو من مجلد شقيق."""
    _v = _os.environ.get(_env)
    if _v:
        return _Path(_v)
    for _n in _names:
        _c = _base.parent / _n
        if _c.is_dir():
            return _c
    return _base.parent / _names[0]
SITE = _tree("SITE_DIR", _ROOT, "seawatch", "site")

import ast
import re
from pathlib import Path

G = Path(f"{SITE}/generator")
B = Path(f"{BRAIN}")

# الترتيب الجديد: (مفتاح المولّد، العنوان الكامل، الإلزام)
ORDER = [
    ("ما تغيّر", "ما تغيّر منذ التقرير السابق",
     "جديد · تصنيف تغيّر · أُغلق · متابعة، مع الرمز الثابت للمرجع"),
    ("الخلاصة القيادية", "الخلاصة القيادية", "ثلاثة أسطر كحد أقصى"),
    ("بطاقة القرار", "بطاقة القرار", "ما تغيّر · مستوى الخطر · المطلوب فورًا · ما يُراقب · أساس التقدير"),
    ("التوزيع الجغرافي", "التوزيع الجغرافي — الخريطة التشغيلية", "الخريطة التشغيلية وجدول التوزيع"),
    ("المؤشرات الرقمية", "المؤشرات الرقمية", "كتلة `indicators`: المؤشر · الحالي · السابق · الاتجاه · الدلالة"),
    ("تقييم التهديد", "تقييم مستوى التهديد", "مستوى الخطر وسببه وحدود التقدير"),
    ("الأثر التشغيلي", "الأثر التشغيلي", "إجراءات قابلة للتنفيذ"),
    ("الوقائع الأمنية الجديدة", "الوقائع الأمنية الجديدة", "كتلة `event_keys` وبطاقات الوقائع بعلامات نوع البند"),
    ("النشرات والتحذيرات", "النشرات والتحذيرات الرسمية", "نشرات استشارية / تحذير للملاحة بالصيغة المعتمدة"),
    ("سجل IMO", "سجل IMO والحوادث المؤكدة", "مقارنة بالعينة السابقة وإشارة صريحة عند عدم المستجد"),
    ("الفرضيات المتنافسة", "الفرضيات المتنافسة والإسناد", "كتلة `hypotheses`: المؤيد · المعارض · درجة الاحتمال"),
    ("اتجاهات الحركة والتكدس", "اتجاهات الحركة والرسو والتكدس الملاحي", "كتلة `timeline` لكل أيام الفترة"),
    ("المجهولات والفجوات", "المجهولات والفجوات", "كتلة `gaps`: الفجوة · الجهة القادرة على الحسم · الأثر"),
    ("المراقبة المستمرة", "المراقبة المستمرة", "ما لا مستجد فيه يُنقل إلى هنا بسطر واحد"),
    ("الخلفية المستمرة", "الخلفية المستمرة", "وقائع أقدم ما زال أثرها مؤثرًا فقط"),
    ("المصادر وحالة الفحص", "المصادر وحالة الفحص", "37 مصدرًا بحالة كل مصدر"),
]
LAYERS = [
    ("الطبقة الأولى — القرار والصورة", [1, 2, 3, 4, 5, 6, 7]),
    ("الطبقة الثانية — الوقائع", [8, 9, 10]),
    ("الطبقة الثالثة — التحليل", [11, 12, 13]),
    ("الطبقة الرابعة — الدعم والمصادر", [14, 15, 16]),
]
applied = []

# ---------- 1) المولّد الموحّد ----------
p = G / "build_report.py"
s = p.read_text(encoding="utf-8")
new_list = "    order = [\n" + "".join(
    f'        "{k}",' + ("\n" if i % 4 == 3 else " ") for i, (k, _, _) in enumerate(ORDER)
) + "\n    ]\n"
s2 = re.sub(r"    order = \[\n(?:.*\n)*?    \]\n", new_list, s, count=1)
if s2 == s:
    raise SystemExit("✘ لم يُطابق قائمة الترتيب في المولّد")
s = s2
s = s.replace(
    "    # ترتيب الأقسام وفق مسار القرار (الترتيب مستقر، والأقسام غير المعروفة تبقى في آخرها)",
    "    # ترتيب الأقسام بالأهمية: القرار والصورة ← الوقائع ← التحليل ← الدعم\n"
    "    # (الترتيب مستقر، والأقسام غير المعروفة تبقى في آخرها)",
)
p.write_text(s, encoding="utf-8")
ast.parse(s)
applied.append("المولّد: قائمة الترتيب الجديدة")

# ---------- 2) جدول الأقسام في 30-structure ----------
p = B / "sections/30-structure.md"
s = p.read_text(encoding="utf-8")
rows = []
n = 0
for layer, idxs in LAYERS:
    rows.append(f"\n**{layer}:**\n")
    rows.append("| # | القسم | ما يُلزم به |")
    rows.append("|---:|---|---|")
    for i in idxs:
        n += 1
        _, title, req = ORDER[i - 1]
        rows.append(f"| {n} | {title} | {req} |")
    rows.append("")
table = "\n".join(rows).strip() + "\n"
s2 = re.sub(
    r"\| # \| القسم \| ما يُلزم به \|\n\|---:\|---\|---\|\n(?:\|.*\n)+",
    table,
    s,
    count=1,
)
if s2 == s:
    raise SystemExit("✘ لم يُطابق جدول الأقسام")
s = s2
s = s.replace(
    "**ترتيب الأقسام المعتمد، ويطبّقه المولّد آليًا:**",
    "**ترتيب الأقسام المعتمد بالأهمية، ويطبّقه المولّد آليًا:**\n\n"
    "> مبدأ الترتيب: ما يحتاجه القارئ أولًا يأتي أولًا. القرار والصورة العامة (الخلاصة · الخريطة التشغيلية · المؤشرات · التهديد · الأثر) ثم الوقائع ثم التحليل ثم الدعم. "
    f"الخريطة التشغيلية تفتح الصورة الجغرافية قبل سرد الوقائع. الترتيب قابل للتعديل من موضع واحد: قائمة `order` في `{SITE}/generator/build_report.py`.",
)
p.write_text(s, encoding="utf-8")
applied.append("30-structure: جدول الطبقات الأربع")

# ---------- 3) قائمة الترتيب في report-blocks ----------
p = B / "appendices/report-blocks.md"
s = p.read_text(encoding="utf-8")
lst = "## أولًا: ترتيب الأقسام المعتمد (الأهمية أولًا)\n" \
      "المولّد يرتب الأقسام تلقائيًا وفق هذا الترتيب، وما لا يطابق عنوانه يبقى في آخر التقرير:\n"
for i, (_, title, _) in enumerate(ORDER, 1):
    lst += f"{i}. {title}\n"
s2 = re.sub(
    r"## أولًا: ترتيب الأقسام المعتمد.*?\n(?=## )",
    lst + "\n",
    s,
    count=1,
    flags=re.S,
)
if s2 == s:
    raise SystemExit("✘ لم يُطابق قائمة الترتيب في report-blocks")
p.write_text(s2, encoding="utf-8")
applied.append("report-blocks: قائمة الترتيب الجديدة")

# ---------- 4) قاعدة ك1 في 40-blocks ----------
p = B / "sections/40-blocks.md"
s = p.read_text(encoding="utf-8")
chain = " ← ".join(t.replace(" — الخريطة التشغيلية", "") for _, t, _ in ORDER)
s2 = re.sub(
    r"- \*\*ترتيب الأقسام وفق مسار القرار:\*\*.*?\n",
    f"- **ترتيب الأقسام بالأهمية (القرار والصورة ← الوقائع ← التحليل ← الدعم):** {chain}. "
    "يحفظ المولّد هذا الترتيب آليًا، فالمطلوب الالتزام بصيغة العناوين المعتمدة.\n",
    s,
    count=1,
    flags=re.S,
)
if s2 == s:
    raise SystemExit("✘ لم تُطابق قاعدة ك1")
p.write_text(s2, encoding="utf-8")
applied.append("40-blocks: قاعدة ك1")

# ---------- 5) إعادة ترتيب أرشيف تقرير 12 أكتوبر ----------
p = B / "reports/2026-10-12-sectioned.md"
s = p.read_text(encoding="utf-8")
parts = re.split(r"(?m)^(?=## )", s)
head, secs = parts[0], parts[1:]
if not secs:
    raise SystemExit("✘ لا أقسام في ملف التقرير")

def rank(sec):
    title = sec.split("\n", 1)[0]
    for i, (k, full, _) in enumerate(ORDER):
        if k in title or full.split(" — ")[0] in title:
            return i
    return len(ORDER)

secs.sort(key=rank)
p.write_text(head + "".join(secs), encoding="utf-8")
applied.append(f"أرشيف 12 أكتوبر: أُعيد ترتيب {len(secs)} قسمًا")

print("نُفِّذ:")
for a in applied:
    print("  ✔", a)
print("\nالترتيب الجديد:")
for i, (_, t, _) in enumerate(ORDER, 1):
    print(f"  {i:>2}. {t}")