#!/usr/bin/env python3
"""يعيد نطاق أرضية الأصول إلى الجذر القانوني ويمنع الجذر الأرشيفي.

العطل: `tools/governing-assets.txt` كان يوجّه كل أصول المشروع إلى الأرشيف
`/home/ubuntu/brain-marine-news`، فقاس الحارس شجرةً أرشيفية متباعدة وأعلن
«نقص في أصل معتمد» لمنع خطوة G000 — والجذر القانوني هو `mda-marine-system/brain`.

الإصلاح: رمز `{BRAIN}` يُستبدل بالجذر القانوني، وأي نمط يشير إلى الجذر الأرشيفي
يفشل مغلقًا برمز 2 برسالة صريحة.
"""
from __future__ import annotations

import pathlib

B = pathlib.Path(__file__).resolve().parent.parent.parent
CONFIG = B / "tools" / "governing-assets.txt"
VALIDATOR = B / "validators" / "check_asset_floor.py"
LEGACY = "/home/ubuntu/brain-marine-news"

OLD_ANCHOR = '''    DEFAULT_CONFIG = PROJECT / "tools" / "governing-assets.txt"'''

CONST_LINE = '''    DEFAULT_CONFIG = PROJECT / "tools" / "governing-assets.txt"
    LEGACY_ROOTS = ("/home/ubuntu/brain-marine-news",)
'''
# ملاحظة: المسافة البادئة في الثابت أعلاه تُصحَّح بعد الاستبدال (المستوى الأعلى).

OLD_SCOPE = '''        kind, _, pattern = line.partition(" ")
        pattern = pattern.strip()
        if kind == "GLOB":'''

NEW_SCOPE = '''        kind, _, pattern = line.partition(" ")
        pattern = pattern.strip()
        pattern = pattern.replace("{BRAIN}", PROJECT.as_posix())
        if any(pattern.startswith(root) for root in LEGACY_ROOTS):
            print(f"✘ أصل حاكم يشير إلى جذر أرشيفي: {pattern}")
            print("   الحدّ: الجذر القانوني هو brain وحده؛ صحّح tools/governing-assets.txt")
            raise SystemExit(2)
        if kind == "GLOB":'''


def main() -> int:
    text = CONFIG.read_text(encoding="utf-8")
    if LEGACY in text:
        text = text.replace(LEGACY, "{BRAIN}")
        text = text.replace(
            "# __pycache__ and *.pyc are excluded because they are generated bytecode, not governing source assets.",
            "# {BRAIN} = الجذر القانوني (مجلد brain). لا تُكتب مسارات أرشيفية هنا.\n"
            "# __pycache__ and *.pyc are excluded because they are generated bytecode, not governing source assets.",
        )
        CONFIG.write_text(text, encoding="utf-8")
        print("   ✔ قائمة الأصول تشير إلى {BRAIN}")
    else:
        print("   = قائمة الأصول مطبَّقة مسبقًا")

    t = VALIDATOR.read_text(encoding="utf-8")
    if "LEGACY_ROOTS" in t:
        print("   = الحارس محصَّن مسبقًا")
    else:
        if OLD_ANCHOR not in t or OLD_SCOPE not in t:
            print("   ✘ لم يُعثر على موضع الترقيع في الحارس")
            return 2
        t = t.replace(OLD_ANCHOR, CONST_LINE.replace("    DEFAULT_CONFIG", "DEFAULT_CONFIG")
                      .replace('LEGACY_ROOTS = ("/home/ubuntu/brain-marine-news",)', 'LEGACY_ROOTS = ("/home/ubuntu/brain-marine-news",)'), 1)
        t = t.replace(OLD_SCOPE, NEW_SCOPE, 1)
        VALIDATOR.write_text(t, encoding="utf-8")
        print("   ✔ الحارس يفشل مغلقًا على أي مسار أرشيفي")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())