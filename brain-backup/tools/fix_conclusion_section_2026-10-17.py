#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""تنظيف قسم «الاستنتاج» في تقرير GFS: إزالة ما لا يخص الاستنتاج.

التغييرات:
  1) حذف جملة الوقائع من الاستنتاج: «وتكررت الإصابات والأضرار ... وفق المتاح.»
  2) تصحيح «خطا» إلى «خطّا».
  3) حذف بند «الأثر التشغيلي» كاملًا من داخل قسم الاستنتاج.
  4) حذف بند «مؤشرات التحذير المبكر» كاملًا من داخل قسم الاستنتاج.
ويُحفظ النص المحذوف في ملف مستقل لاستخدامه في موضعه الصحيح.
"""
from pathlib import Path
import shutil
from docx import Document

ROOT = Path('/home/ubuntu/brain-marine-news')
SRC = ROOT / 'reports/docx/تقرير-GFS-PRIDE-GFS-GISELLE-نهائي-2026-10-17.docx'
BAK = ROOT / 'reports/docx/_backup/تقرير-GFS-PRIDE-GFS-GISELLE-نهائي-2026-10-17_قبل-حذف-بنود-الاستنتاج.docx'
REMOVED = ROOT / 'audit/day5/المحذوف-من-الاستنتاج-2026-10-17.md'

NEW16 = (
    'الاستنتاج. تدير الجهة نفسها السفينتين، وخطّا خدمتهما متقاربان. '
    'وهذا يرفع احتمال أن نمط الاختيار لا يقتصر على سفينة بعينها؛ والتقييم: مرجّح. '
    'ولا يثبت ذلك جهة التنفيذ. وتربط مصادر مهنية الواقعتين بسفن مرتبطة بالإمارات، '
    'من دون الجزم بأن الواقعتين استهدفتا هذه الفئة تحديدًا؛ والقصد غير مثبت. '
    'ويبقى الحطام خطرًا ملاحيًا بعد الغرق، وتستوجب الحاويات الطافية تحذيرًا للملاحين. '
    'ويُحتمل أن تزيد المخاطر البيئية والمطالبات التأمينية؛ '
    'ولم يثبت ارتفاع أقساط التأمين بسبب الواقعتين.'
)

def main():
    BAK.parent.mkdir(parents=True, exist_ok=True)
    REMOVED.parent.mkdir(parents=True, exist_ok=True)
    if not BAK.exists():
        shutil.copy2(SRC, BAK)

    d = Document(str(SRC))
    ps = d.paragraphs

    # 1) تحديد فقرات القسم الرابع بالاسم لا بالرقم (أمانًا لو تغيّر الترتيب)
    idx = {}
    for i, p in enumerate(ps):
        t = p.text.strip()
        for key in ('الاستنتاج.', 'الأثر التشغيلي.', 'مؤشرات التحذير المبكر.', 'الخلاصة.'):
            if t.startswith(key) and key not in idx:
                idx[key] = i
    missing = [k for k in ('الاستنتاج.', 'الأثر التشغيلي.', 'مؤشرات التحذير المبكر.', 'الخلاصة.') if k not in idx]
    if missing:
        raise SystemExit(f'لم أجد الفقرات: {missing}')

    i_concl = idx['الاستنتاج.']
    i_impact = idx['الأثر التشغيلي.']
    i_indic = idx['مؤشرات التحذير المبكر.']
    i_summary = idx['الخلاصة.']

    assert i_concl < i_impact < i_indic < i_summary, 'ترتيب الأقسام غير متوقع'

    removed_impact = ps[i_impact].text.strip()
    removed_indic = ps[i_indic].text.strip()

    # 2) نص الاستنتاج الجديد
    p16 = ps[i_concl]
    old16 = p16.text.strip()
    if p16.runs:
        p16.runs[0].text = NEW16
        for r in p16.runs[1:]:
            r.text = ''
    else:
        p16.add_run(NEW16)

    # 3) حذف البندين من قسم الاستنتاج
    for i in (i_indic, i_impact):
        el = ps[i]._element
        el.getparent().remove(el)

    d.save(str(SRC))

    # 4) حفظ المحذوف
    REMOVED.write_text(
        '# المحذوف من قسم «الاستنتاج» — تقرير GFS (17 أكتوبر 2026)\n\n'
        '**السبب:** هذه البنود لا تخص الاستنتاج؛ فالأول تقدير أثر تشغيلي، والثاني رصد مؤشرات مستقبلية.\n'
        'ويُوصى بوضعهما في قسمين مستقلين خارج الاستنتاج.\n\n'
        '## 1) جملة وقائع أُزيلت من نص الاستنتاج\n\n'
        '> وتكررت الإصابات والأضرار في بعض الوقائع. وسُجل الحريق وتعطل المحرّك في سفن معينة، '
        'ولا ينطبق ذلك على «GFS GISELLE» وفق المتاح.\n\n'
        '**الموضع المقترح:** بند «المثبت رسميًا / النتائج» أو جدول ٣ (السفن المرتبطة بالواقعة).\n\n'
        '## 2) بند «الأثر التشغيلي» (منقول كما هو)\n\n'
        f'> {removed_impact}\n\n'
        '**الموضع المقترح:** قسم مستقل بعنوان «الأثر التشغيلي» قبل الاستنتاج.\n\n'
        '## 3) بند «مؤشرات التحذير المبكر» (منقول كما هو)\n\n'
        f'> {removed_indic}\n\n'
        '**الموضع المقترح:** قسم مستقل بعنوان «المراقبة المستمرة» بعد الخلاصة، أو داخل «الإجراء المطلوب».\n\n'
        '---\n\n'
        '## نص الاستنتاج قبل التنظيف (للرجوع)\n\n'
        f'> {old16}\n\n'
        '## نص الاستنتاج بعد التنظيف\n\n'
        f'> {NEW16}\n',
        encoding='utf-8')

    print('تم التعديل.')
    print('الاستنتاج الجديد بمجموع الكلمات:', len(NEW16.split()))
    print('عدد فقرات الملف الآن:', len(Document(str(SRC)).paragraphs))

if __name__ == '__main__':
    main()