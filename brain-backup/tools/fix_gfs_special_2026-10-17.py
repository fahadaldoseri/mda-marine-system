def iter_paragraphs(doc):
    for p in doc.paragraphs:
        yield p
    for t in doc.tables:
        for row in t.rows:
            for c in row.cells:
                for p in c.paragraphs:
                    yield p
                for it in c.tables:
                    for r2 in it.rows:
                        for c2 in r2.cells:
                            for p2 in c2.paragraphs:
                                yield p2


def set_para_text(p, new_text):
    """يضع النص في أول run مع الحفاظ على تنسيقه، ويمسح البقية."""
    runs = p.runs
    if not runs:
        p.add_run(new_text)
        return
    runs[0].text = new_text
    for r in runs[1:]:
        r.text = ""


def replace_in_para(p, old, new):
    """استبدال يحافظ على الأنماط إن كان الهدف داخل run واحد."""
    for r in p.runs:
        if old in r.text:
            r.text = r.text.replace(old, new)
            return True
    full = "".join(r.text for r in p.runs)
    if old in full:
        set_para_text(p, full.replace(old, new))
        return True
    return False


def main():
    d = Document(str(SRC))
    log = []
    paras = list(iter_paragraphs(d))

    for old, new in REPL:
        done = 0
        for p in paras:
            if old[:40] in "".join(r.text for r in p.runs):
                if replace_in_para(p, old, new):
                    done += 1
        log.append((f"استبدال: {old[:45]}…", done))

    for anchor, new_text in REWRITE:
        done = 0
        for p in paras:
            txt = "".join(r.text for r in p.runs)
            if txt.strip().startswith(anchor[:35]):
                set_para_text(p, new_text)
                done += 1
                break
        log.append((f"إعادة كتابة: {anchor[:45]}…", done))

    # --- ترتيب جدول التسلسل الزمني: 3 أكتوبر قبل 5 أكتوبر ---
    swapped = 0
    for t in d.tables:
        rows = t.rows
        for i in range(len(rows) - 1):
            a = " ".join(c.text for c in rows[i].cells)
            b = " ".join(c.text for c in rows[i + 1].cells)
            if a.startswith("5 أكتوبر 2026") and b.startswith("3 أكتوبر 2026"):
                tr_a = rows[i]._tr
                tr_b = rows[i + 1]._tr
                tr_a.addnext(tr_b)
                swapped += 1
                break
    log.append(("تبديل صفّي 5 أكتوبر و3 أكتوبر", swapped))

    d.save(str(DST))
    for name, n in log:
        print(f"  {'✔' if n else '✗'} {name} → {n}")
    print(f"\nالناتج: {DST}  ({DST.stat().st_size} بايت)")


if __name__ == "__main__":
    main()
