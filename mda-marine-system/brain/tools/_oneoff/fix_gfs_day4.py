def iter_paras(doc):
    for p in doc.paragraphs:
        yield p
    for t in doc.tables:
        for row in t.rows:
            for c in row.cells:
                for p in c.paragraphs:
                    yield p


def set_cell(cell, val):
    for p in cell.paragraphs[1:]:
        p._element.getparent().remove(p._element)
    ps = cell.paragraphs
    if not ps:
        cell.add_paragraph(val)
        return
    p = ps[0]
    if not p.runs:
        p.add_run(val)
        return
    p.runs[0].text = val
    for r in p.runs[1:]:
        r.text = ""


def set_para_text(p, new_text):
    runs = p.runs
    if not runs:
        p.add_run(new_text)
        return
    runs[0].text = new_text
    for r in runs[1:]:
        r.text = ""


def replace_in_para(p, old, new):
    for r in p.runs:
        if old in r.text:
            r.text = r.text.replace(old, new)
            return True
    full = "".join(r.text for r in p.runs)
    if old in full:
        set_para_text(p, full.replace(old, new))
        return True
    return False


