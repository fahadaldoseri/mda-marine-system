_KEYS = sorted(IMPERATIVES, key=len, reverse=True)
_PATTERNS = [
    (re.compile(r"(?<![\u0621-\u064A])" + re.escape(k) + r"(?![\u0621-\u064A])"), IMPERATIVES[k])
    for k in _KEYS
]


def to_third_person(text):
    """يُرجع النص بأسلوب الغائب؛ والنص غير العربي يمرّ كما هو."""
    if not text or not isinstance(text, str):
        return text
    out = text
    for pat, rep in _PATTERNS:
        out = pat.sub(rep, out)
    return out


def violations(text):
    """أفعال الأمر المخاطبة الموجودة في النص (للحارس والقياس)."""
    if not text:
        return []
    found = []
    for pat, _rep in _PATTERNS:
        found += pat.findall(text)
    return sorted(set(found))
