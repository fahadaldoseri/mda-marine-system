"""تطبيع عنوان الإصدار اليومي — مصدر واحد للحقيقة (إصلاح ك-595).

المشكلة الجذرية: كان التمييز بين «عنوان يومي عام» و«عنوان مخصّص» يجري بمقارنة
قائمة ثابتة، فعنوان مثل
«التقرير اليومي لأمن الملاحة والأوضاع الراهنة في المنطقة — 29 أكتوبر 2026»
يُعامل عنوانًا مخصّصًا، فيحتاج ترجمة في المعجم الإنجليزي ويُسقط بناء الإصدارات
القديمة برسالة «نصوص عربية بلا ترجمة».

الحل: التمييز نمطي — أي عنوان يبدأ ببادئة يومية معتمدة، وربما تلحق بها كلمات
عربية وتاريخ، يُطبَّع إلى الاسم المعتمد للتقرير اليومي. العنوان المخصّص الحقيقي
(لا يبدأ ببادئة يومية) يبقى كما هو.
"""
from __future__ import annotations

import re

# الاسم المعتمد للتقرير اليومي (قرار صاحب القرار — 18 أكتوبر 2026)
DAILY_TITLE = "التقرير اليومي للأمن البحري والأوضاع الراهنة في المنطقة"

# بادئات يومية عامة كانت تُكتب في بيانات الإصدارات السابقة
DAILY_PLACEHOLDERS = [
    "التقرير الصباحي اليومي",
    "التقرير اليومي لأمن الملاحة والأوضاع الراهنة في المنطقة",
    "التقرير اليومي للأمن البحري والأوضاع الراهنة في المنطقة",
    "التقرير اليومي لأمن الملاحة",
    "التقرير اليومي للأمن البحري",
    "التقرير اليومي",
    "تقرير أمن الملاحة اليومي",
    "تقرير اليوم",
]

_PREFIXES = "|".join(re.escape(x) for x in DAILY_PLACEHOLDERS)
_ARABIC = "\u0600-\u06FF"
# بعد البادئة: كلمات عربية ومسافات وعلامات فصل، ثم تاريخ عربي أو ميلادي اختياري
_DAILY_RE = re.compile(
    rf"^\s*(?:{_PREFIXES})"
    rf"(?:[\s{_ARABIC}،:·]+)?"
    rf"(?:\s*[—–\-]\s*\d{{1,2}}\s+[{_ARABIC}]+\s+\d{{4}}"
    rf"|\s*[—–\-]\s*\d{{4}}-\d{{2}}-\d{{2}})?\s*$"
)


def is_daily_placeholder(value: str | None) -> bool:
    """هل القيمة عنوان يومي عام (مع أو بلا تاريخ) لا عنوانًا مخصّصًا؟"""
    text = (value or "").strip()
    if not text:
        return False
    if text in DAILY_PLACEHOLDERS:
        return True
    return bool(_DAILY_RE.match(text))


def normalize_daily_title(value: str | None, fallback: str = DAILY_TITLE) -> str:
    """يعيد الاسم المعتمد للتقرير اليومي إذا كانت القيمة عنوانًا يوميًا عامًا."""
    text = (value or "").strip()
    if not text or is_daily_placeholder(text):
        return fallback
    return text